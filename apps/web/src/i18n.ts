export const DICTS: Record<Locale, Dict> = { en, hi };
export type TKey = keyof Dict;

/** Locale context: current locale plus a setter. */
export const LocaleContext = createContext<{ locale: Locale; setLocale: (l: Locale) => void }>({ locale: 'hi', setLocale: () => undefined });

/** Hook returning the translator for the current locale. */
export function useT(): { t: (k: TKey) => string; locale: Locale; setLocale: (l: Locale) => void } {
  const ctx = useContext(LocaleContext);
  return { t: (k) => DICTS[ctx.locale][k], locale: ctx.locale, setLocale: ctx.setLocale };
}

/** Picks the localised variant of a {en, hi} object from the API. */
export function pick(v: { en: string; hi: string } | undefined, locale: Locale): string {
  return v ? v[locale] : '';
}

/** Date-time formatting in the user's locale, Indian time zone. */
export function fmtTime(iso: string | Date, locale: Locale): string {
  return new Date(iso).toLocaleString(locale === 'hi' ? 'hi-IN' : 'en-IN', { timeZone: 'Asia/Kolkata', dateStyle: 'medium', timeStyle: 'short' });
}
